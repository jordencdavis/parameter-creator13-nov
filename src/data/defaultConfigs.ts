export function createStarterConfig(tabSlug: string): TabConfigSchema {
  const title = tabSlug
    .split('_')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');

  return {
    tab_id: tabSlug,
    tab_title: title || tabSlug,
    description: `Dynamic data generator schema for ${tabSlug}`,
    version: '1.0',
    fields: [
      {
        id: 'source_columns',
        label: 'Source Columns',
        type: 'checkbox_group',
        options: ['id', 'name', 'value', 'status', 'timestamp'],
        default: ['id', 'name', 'value'],
      },
      {
        id: 'num_records',
        label: 'Number of Records',
        type: 'number',
        min: 1,
        max: 100,
        default: 5,
      },
    ],
    generator_type: 'generic',
  };
}
